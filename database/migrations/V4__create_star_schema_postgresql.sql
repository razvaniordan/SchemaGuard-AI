CREATE SCHEMA IF NOT EXISTS analytics;

-- =============================================================================
-- DIMENSION: Date
-- Grain: one row per calendar date
-- =============================================================================
CREATE TABLE analytics.dim_date (
    date_key INT NOT NULL, -- YYYYMMDD
    full_date DATE NOT NULL,
    day_number INT NOT NULL,
    month_number INT NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    quarter_number INT NOT NULL,
    year_number INT NOT NULL,
    is_weekend CHAR(1) NOT NULL,

    CONSTRAINT pk_dim_date PRIMARY KEY (date_key),
    CONSTRAINT uq_dim_date_full_date UNIQUE (full_date),
    CONSTRAINT ck_dim_date_is_weekend CHECK (is_weekend IN ('Y', 'N'))
);

-- =============================================================================
-- DIMENSION: Region
-- Source: public.regions
-- =============================================================================
CREATE TABLE analytics.dim_region (
    region_key BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_region_code VARCHAR(30) NOT NULL,
    region_name VARCHAR(100) NOT NULL,
    description VARCHAR(255),

    CONSTRAINT pk_dim_region PRIMARY KEY (region_key),
    CONSTRAINT uq_dim_region_source_code UNIQUE (source_region_code)
);

-- =============================================================================
-- DIMENSION: Country - SCD Type 2
-- Source: public.countries + public.regions
-- =============================================================================
CREATE TABLE analytics.dim_country (
    country_key BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_country_code CHAR(2) NOT NULL,

    country_name VARCHAR(100) NOT NULL,
    region_code VARCHAR(30) NOT NULL,
    region_name VARCHAR(100),

    effective_from TIMESTAMP NOT NULL,
    effective_to TIMESTAMP,
    is_current CHAR(1) NOT NULL DEFAULT 'Y',
    version_number INT NOT NULL DEFAULT 1,

    CONSTRAINT pk_dim_country PRIMARY KEY (country_key),

    CONSTRAINT ck_dim_country_current CHECK (is_current IN ('Y', 'N')),
    CONSTRAINT ck_dim_country_dates CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT uq_dim_country_version UNIQUE (source_country_code, effective_from)
);

CREATE UNIQUE INDEX uq_dim_country_current ON analytics.dim_country (source_country_code)
WHERE is_current = 'Y';

-- =============================================================================
-- DIMENSION: Client
