-- =============================================================================
-- MATERIALIZED VIEW: Monthly fee savings
-- Used for dashboard totals by month.
-- =============================================================================
CREATE MATERIALIZED VIEW analytics.mv_monthly_fee_savings AS
SELECT
    d.year_number,
    d.month_number,
    d.month_name,

    COUNT(*) AS transaction_count,
    SUM(f.transaction_amount) AS total_transaction_amount,
    SUM(f.current_interchange_fee_amount) AS total_current_fee_amount,
    SUM(f.optimal_interchange_fee_amount) AS total_optimal_fee_amount,
    SUM(f.saving_amount) AS total_saving_amount,
    AVG(f.saving_percentage) AS avg_saving_percentage
FROM analytics.fact_transaction_analysis f
JOIN analytics.dim_date d
    ON d.date_key = f.authorization_date_key
GROUP BY
    d.year_number,
    d.month_number,
    d.month_name
WITH NO DATA;

CREATE UNIQUE INDEX uq_mv_monthly_fee_savings
ON analytics.mv_monthly_fee_savings (year_number, month_number);

-- =============================================================================
-- MATERIALIZED VIEW: Merchant optimization summary
-- Used to identify merchants with highest potential savings.
-- =============================================================================
CREATE MATERIALIZED VIEW analytics.mv_merchant_optimization_summary AS
SELECT
    m.merchant_key,
    m.source_merchant_id,
    m.merchant_name,
    m.mcc_code,
    m.mcc_description,

    COUNT(*) AS transaction_count,
    SUM(f.transaction_amount) AS total_transaction_amount,
    SUM(f.current_interchange_fee_amount) AS total_current_fee_amount,
    SUM(f.optimal_interchange_fee_amount) AS total_optimal_fee_amount,
    SUM(f.saving_amount) AS total_saving_amount,
    AVG(f.saving_percentage) AS avg_saving_percentage
FROM analytics.fact_transaction_analysis f
JOIN analytics.dim_merchant m
    ON m.merchant_key = f.merchant_key
GROUP BY
    m.merchant_key,
    m.source_merchant_id,
    m.merchant_name,
    m.mcc_code,
    m.mcc_description
WITH NO DATA;

CREATE UNIQUE INDEX uq_mv_merchant_optimization_summary
ON analytics.mv_merchant_optimization_summary (merchant_key);

-- =============================================================================
-- MATERIALIZED VIEW: Category transition summary
-- Used to show movement from current category to optimal category.
-- Example:
-- Ecom Non-Secure Credit -> Ecom Secure Preferred Credit
-- =============================================================================
CREATE MATERIALIZED VIEW analytics.mv_category_transition_summary AS
SELECT
    current_cat.category_key AS current_category_key,
    current_cat.category_name AS current_category_name,

    optimal_cat.category_key AS optimal_category_key,
    optimal_cat.category_name AS optimal_category_name,

    COUNT(*) AS transaction_count,
    SUM(f.current_interchange_fee_amount) AS total_current_fee_amount,
    SUM(f.optimal_interchange_fee_amount) AS total_optimal_fee_amount,
    SUM(f.saving_amount) AS total_saving_amount,
    AVG(f.saving_percentage) AS avg_saving_percentage
FROM analytics.fact_transaction_analysis f
JOIN analytics.dim_interchange_category current_cat
    ON current_cat.category_key = f.current_category_key
JOIN analytics.dim_interchange_category optimal_cat
    ON optimal_cat.category_key = f.optimal_category_key
GROUP BY
    current_cat.category_key,
    current_cat.category_name,
    optimal_cat.category_key,
    optimal_cat.category_name
WITH NO DATA;

CREATE UNIQUE INDEX uq_mv_category_transition_summary
ON analytics.mv_category_transition_summary (
    current_category_key,
    optimal_category_key
);