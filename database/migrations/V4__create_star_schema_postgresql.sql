-- =============================================================================
-- FACT: Transaction Analysis
--
-- Grain:
-- One row per completed transaction analysis.
--
-- Meaning:
-- One row combines:
-- - original transaction
-- - CURRENT interchange result
-- - OPTIMAL interchange result
-- - optimization saving
--
-- Partitioning:
-- Partitioned by authorization_date_key.
-- =============================================================================
CREATE TABLE analytics.fact_transaction_analysis (
    analysis_fact_id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    source_transaction_id BIGINT NOT NULL,
    source_current_result_id BIGINT NOT NULL,
    source_optimal_result_id BIGINT NOT NULL,
    source_optimization_result_id BIGINT NOT NULL,

    authorization_date_key INT NOT NULL,

    client_key BIGINT NOT NULL,
    merchant_key BIGINT NOT NULL,
    card_key BIGINT NOT NULL,
    acquiring_partner_key BIGINT NOT NULL,
    region_key BIGINT NOT NULL,

    current_category_key BIGINT NOT NULL,
    optimal_category_key BIGINT NOT NULL,

    transaction_amount NUMERIC(12, 2) NOT NULL,
    transaction_currency CHAR(3) NOT NULL,
    transaction_channel VARCHAR(30) NOT NULL,
    transaction_mcc_code VARCHAR(4) NOT NULL,
    transaction_status VARCHAR(30) NOT NULL,

    is_3ds_authenticated CHAR(1) NOT NULL,
    clearing_hours NUMERIC(10, 2), -- it stores how long did it take for the transaction to move from authorization to clearing/settlement ex.: value 48 for 48 hours
    clearing_time_condition VARCHAR(30),

    current_fee_percentage NUMERIC(7, 4) NOT NULL,
    current_interchange_fee_amount NUMERIC(12, 2) NOT NULL,

    optimal_fee_percentage NUMERIC(7, 4) NOT NULL,
    optimal_interchange_fee_amount NUMERIC(12, 2) NOT NULL,

    saving_amount NUMERIC(12, 2) NOT NULL,
    saving_percentage NUMERIC(7, 4),

    recommendation_count INT NOT NULL DEFAULT 0,
    top_recommendation_type VARCHAR(50),
    top_recommendation_text VARCHAR(500),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT pk_fact_transaction_analysis PRIMARY KEY (analysis_fact_id, authorization_date_key),

    CONSTRAINT uq_fact_transaction_analysis_source UNIQUE (source_transaction_id, authorization_date_key),

    CONSTRAINT fk_fact_authorization_date FOREIGN KEY (authorization_date_key) REFERENCES analytics.dim_date (date_key),
    CONSTRAINT fk_fact_client FOREIGN KEY (client_key) REFERENCES analytics.dim_client (client_key),
    CONSTRAINT fk_fact_merchant FOREIGN KEY (merchant_key) REFERENCES analytics.dim_merchant (merchant_key),
    CONSTRAINT fk_fact_card FOREIGN KEY (card_key) REFERENCES analytics.dim_card (card_key),
    CONSTRAINT fk_fact_acquiring_partner FOREIGN KEY (acquiring_partner_key) REFERENCES analytics.dim_acquiring_partner (acquiring_partner_key),
    CONSTRAINT fk_fact_region FOREIGN KEY (region_key) REFERENCES analytics.dim_region (region_key),
    CONSTRAINT fk_fact_current_category FOREIGN KEY (current_category_key) REFERENCES analytics.dim_interchange_category (category_key),
    CONSTRAINT fk_fact_optimal_category FOREIGN KEY (optimal_category_key) REFERENCES analytics.dim_interchange_category (category_key),

    CONSTRAINT ck_fact_transaction_amount CHECK (transaction_amount > 0),
    CONSTRAINT ck_fact_transaction_mcc_code CHECK (transaction_mcc_code ~ '^[0-9]{4}$'),
    CONSTRAINT ck_fact_fee_amounts CHECK (current_interchange_fee_amount >= 0 AND optimal_interchange_fee_amount >= 0 AND saving_amount >= 0),
    CONSTRAINT ck_fact_3ds CHECK (is_3ds_authenticated IN ('Y', 'N')),
    CONSTRAINT ck_fact_clearing_condition CHECK (clearing_time_condition IS NULL OR clearing_time_condition IN ('LTE_24H', 'GT_24H'))
)
PARTITION BY RANGE (authorization_date_key);

